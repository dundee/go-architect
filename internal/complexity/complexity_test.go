func TestCalculateInProcess(t *testing.T) {
	dir := t.TempDir()

	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/demo\n\ngo 1.24\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "main.go"), []byte(`package main

func simple() int {
	return 1
}

func branching(x int) int {
	if x > 0 {
		for i := 0; i < x; i++ {
			if i%2 == 0 {
				return i
			}
		}
	}
	return 0
}
`), 0o644))

	require.NoError(t, os.MkdirAll(filepath.Join(dir, "sub"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "sub", "helper.go"), []byte(`package sub

func helper(a, b bool) int {
	if a && b {
		return 1
	}
	return 0
}
`), 0o644))

	// Test files and vendor should be ignored
	require.NoError(t, os.WriteFile(filepath.Join(dir, "main_test.go"), []byte(`package main
func TestHuge() {
	if true { if true { if true { if true {} } } }
}
`), 0o644))

	report, err := Calculate(dir, "example.com/demo", 2)
	require.NoError(t, err)
	require.NotNil(t, report)

	require.Greater(t, report.Cyclomatic.AverageComplexity, 1.0)
	require.Len(t, report.Cyclomatic.ComplexityDetails, 2)
	require.Equal(t, "branching", report.Cyclomatic.ComplexityDetails[0].Function)
	require.Equal(t, "example.com/demo", report.Cyclomatic.ComplexityDetails[0].Package)

	require.Greater(t, report.Cognitive.AverageComplexity, 0.0)
	require.Len(t, report.Cognitive.ComplexityDetails, 2)
	require.Equal(t, "branching", report.Cognitive.ComplexityDetails[0].Function)
}

func TestCalculateWorkerPoolDeterministic(t *testing.T) {
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/many\n\ngo 1.24\n"), 0o644))

	for i := 0; i < 24; i++ {
		sub := filepath.Join(dir, "pkg", string(rune('a'+i)))
		require.NoError(t, os.MkdirAll(sub, 0o755))
		src := "package p\nfunc fn(x int) int {\n\tif x > 0 {\n\t\treturn 1\n\t}\n\treturn 0\n}\n"
		require.NoError(t, os.WriteFile(filepath.Join(sub, "f.go"), []byte(src), 0o644))
	}

	first, err := Calculate(dir, "example.com/many", 5)
	require.NoError(t, err)
	for run := 0; run < 5; run++ {
		next, err := Calculate(dir, "example.com/many", 5)
		require.NoError(t, err)
		require.Equal(t, first, next)
	}
}

func TestIsGeneratedSourceAndFiltering(t *testing.T) {
	require.True(t, IsGeneratedSource([]byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage pb\n")))
	require.True(t, IsGeneratedSource([]byte("//go:build linux\n// Code generated by mockgen. DO NOT EDIT.\npackage mock\n")))
	require.False(t, IsGeneratedSource([]byte("package main\n\n// Code generated by hand. DO NOT EDIT.\nfunc f() {}\n")))
	require.False(t, IsGeneratedSource([]byte("/* Code generated by tool. DO NOT EDIT. */\npackage main\n")))
	require.False(t, IsGeneratedSource([]byte("package main\nfunc main() {}\n")))

	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/gen\n\ngo 1.24\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "hand.go"), []byte("package main\nfunc hand() int { return 1 }\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "gen.pb.go"), []byte(`// Code generated by protoc-gen-go. DO NOT EDIT.

package main

func generatedComplex(x int) int {
	if x > 0 {
		if x > 1 {
			if x > 2 {
				return x
			}
		}
	}
	return 0
}
`), 0o644))

	report, err := Calculate(dir, "example.com/gen", 5)
	require.NoError(t, err)
	require.Len(t, report.Cyclomatic.ComplexityDetails, 1)
	require.Equal(t, "hand", report.Cyclomatic.ComplexityDetails[0].Function)
	require.Equal(t, 1.0, report.Cyclomatic.AverageComplexity)

	perFile, err := CalculatePerFile(dir, "example.com/gen")
	require.NoError(t, err)
	require.Len(t, perFile, 1)
	require.Contains(t, perFile, "hand.go")
	require.NotContains(t, perFile, "gen.pb.go")
}
